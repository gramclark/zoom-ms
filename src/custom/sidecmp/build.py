#!/usr/bin/env python3
"""Build SideCmp: sidechain compression with a live needle gain-reduction meter."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "build"))
from screen_image import Canvas, encode_zoom_rle  # noqa: E402


def draw_scale(canvas, left, right, center, baseline, rise, full_screen=False):
    span = right - center
    previous_y = None
    for x in range(left, right + 1):
        dx = x - center
        y = baseline - (rise * (span * span - dx * dx) // (span * span))
        if previous_y is None:
            canvas.px(x, y)
        else:
            canvas.vline(x, previous_y, y)
        previous_y = y
    if full_screen:
        for db in range(0, 25, 2):
            x = right - ((right - left) * db + 12) // 24
            dx = x - center
            y = baseline - (rise * (span * span - dx * dx) // (span * span))
            tick_length = 4 if db % 6 == 0 else 2
            canvas.vline(x, y, y + tick_length)
        for label, x, y in (
            ("24", 2, 48), ("18", 28, 25), ("12", 60, 5),
            ("6", 93, 25), ("0", 119, 48),
        ):
            canvas.draw_text(label, x, y)
        canvas.draw_text("GR", 3, 2)
    else:
        for x in (left, center - span // 2, center, center + span // 2, right):
            dx = x - center
            y = baseline - (rise * (span * span - dx * dx) // (span * span))
            canvas.vline(x, y, y + 2)
        for label, x in (("24", 46), ("12", 81), ("0", 117)):
            canvas.draw_text(label, x, 56)


def draw_needle_at(canvas, reduction, left, right, center, baseline, rise, thick=True):
    span = right - center
    scaled = min(1.0, max(0.0, reduction / 24.0))
    x = right - int((right - left) * scaled + 0.5)
    dx = x - center
    y = baseline - (rise * (span * span - dx * dx) // (span * span))
    pivot_y = baseline + (2 if span > 40 else 1)
    if thick:
        line(canvas, center - 1, pivot_y, x - 1, y)
        line(canvas, center + 1, pivot_y, x + 1, y)
    line(canvas, center, pivot_y, x, y)
    canvas.filled_circle(center, pivot_y, 1)


def line(canvas, x0, y0, x1, y1):
    dx, sx = abs(x1 - x0), 1 if x0 < x1 else -1
    dy, sy = -abs(y1 - y0), 1 if y0 < y1 else -1
    error = dx + dy
    while True:
        canvas.px(x0, y0)
        if x0 == x1 and y0 == y1:
            break
        twice = 2 * error
        if twice >= dy:
            error += dy
            x0 += sx
        if twice <= dx:
            error += dx
            y0 += sy


def cover():
    c = Canvas()
    bitmap = (HERE / "selection_art.bin").read_bytes()
    if len(bitmap) != 1024:
        raise ValueError("selection_art.bin must contain the full 128x64 bitmap")
    for block in range(8):
        for x in range(128):
            value = bitmap[block * 128 + x]
            for bit in range(8):
                if value & (1 << bit):
                    c.px(x, block * 8 + bit)
    return c


def runtime_background():
    c = Canvas()
    c.rect(1, 1, 126, 62)
    draw_scale(c, 12, 116, 64, 53, 42, full_screen=True)
    return c


def raw(canvas):
    out = bytearray(1024)
    for block in range(8):
        for x in range(128):
            value = 0
            for bit in range(8):
                if canvas.pixels[block * 8 + bit][x]:
                    value |= 1 << bit
            out[block * 128 + x] = value
    return bytes(out)


def c_bytes(name, data):
    rows = [", ".join(f"0x{value:02X}" for value in data[i:i + 16])
            for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n" + ",\n".join(rows) + "\n};\n"


(HERE / "sidecmp_art.h").write_text(
    "/* generated by build.py */\n"
    + c_bytes("SIDECMP_BG", raw(runtime_background()))
)
if "--art-only" in sys.argv:
    raise SystemExit(0)
sys.path.insert(0, str(HERE.parent / "common"))
from zvis_build import build  # noqa: E402

build(HERE, encode_zoom_rle(cover()))
