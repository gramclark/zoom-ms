#!/usr/bin/env python3
"""Build SideCmp: sidechain compression with a live transfer-curve display."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "build"))
from screen_image import Canvas, encode_zoom_rle  # noqa: E402

LEFT, RIGHT, TOP, BOTTOM = 16, 112, 12, 55


def background(title=False):
    c = Canvas()
    c.rect(LEFT, TOP, RIGHT, BOTTOM)
    for x in (40, 64, 88):
        c.vline(x, TOP + 1, BOTTOM - 1)
    for y in (22, 32, 42):
        c.hline(LEFT + 1, RIGHT - 1, y)
    c.draw_text("IN", LEFT - 9, BOTTOM - 4)
    c.draw_text("OUT", LEFT + 2, TOP - 8)
    c.draw_text("GR", 1, 57)
    if title:
        c.draw_text("SIDE CHICK", 64 - 40, 2, scale=2)
        for x in range(LEFT, RIGHT):
            y = BOTTOM - round((x - LEFT) * 0.42)
            c.px(x, y)
    return c


def raw(canvas):
    out = bytearray(1024)
    for block in range(8):
        for x in range(128):
            value = 0
            for bit in range(8):
                if canvas.pixels[block * 8 + bit][x]:
                    value |= 1 << bit
            out[block * 128 + x] = value
    return bytes(out)


def c_bytes(name, data):
    rows = [", ".join(f"0x{value:02X}" for value in data[i:i + 16])
            for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n" + ",\n".join(rows) + "\n};\n"


(HERE / "sidecmp_art.h").write_text(
    "/* generated by build.py */\n"
    + c_bytes("SIDECMP_BG", raw(background()))
)
if "--art-only" in sys.argv:
    raise SystemExit(0)
sys.path.insert(0, str(HERE.parent / "common"))
from zvis_build import build  # noqa: E402

build(HERE, encode_zoom_rle(background(title=True)))
