#!/usr/bin/env python3
"""Build SideCmp: sidechain compression with a live needle gain-reduction meter."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "build"))
from screen_image import Canvas, encode_zoom_rle  # noqa: E402


def meter_tip(reduction):
    scaled = min(1.0, max(0.0, reduction / 24.0))
    x = 102 - int(76 * scaled + 0.5)
    dx = x - 64
    y = 54 - (22 * (1444 - dx * dx) // 1444)
    return x, y


def line(canvas, x0, y0, x1, y1):
    dx, sx = abs(x1 - x0), 1 if x0 < x1 else -1
    dy, sy = -abs(y1 - y0), 1 if y0 < y1 else -1
    error = dx + dy
    while True:
        canvas.px(x0, y0)
        if x0 == x1 and y0 == y1:
            break
        twice = 2 * error
        if twice >= dy:
            error += dy
            x0 += sx
        if twice <= dx:
            error += dx
            y0 += sy


def background(title=False):
    c = Canvas()
    c.rect(14, 18, 114, 62)
    previous_y = None
    for x in range(26, 103):
        dx = x - 64
        y = 54 - (22 * (1444 - dx * dx) // 1444)
        if previous_y is None:
            c.px(x, y)
        else:
            c.vline(x, previous_y, y)
        previous_y = y
    for x, y in ((26, 54), (45, 38), (64, 32), (83, 38), (102, 54)):
        c.vline(x, y, y + 4)
    for label, x, y in (
        ("24", 19, 46), ("18", 39, 31), ("12", 61, 24),
        ("6", 84, 31), ("0", 106, 46), ("GR", 61, 19),
    ):
        c.draw_text(label, x, y)
    if title:
        c.draw_text("PUMP IT", 40, 2, scale=2)
    return c


def draw_needle(canvas, reduction):
    x, y = meter_tip(reduction)
    line(canvas, 64, 56, x, y)


def cover():
    c = background(title=True)
    draw_needle(c, 12.0)
    return c


def raw(canvas):
    out = bytearray(1024)
    for block in range(8):
        for x in range(128):
            value = 0
            for bit in range(8):
                if canvas.pixels[block * 8 + bit][x]:
                    value |= 1 << bit
            out[block * 128 + x] = value
    return bytes(out)


def c_bytes(name, data):
    rows = [", ".join(f"0x{value:02X}" for value in data[i:i + 16])
            for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n" + ",\n".join(rows) + "\n};\n"


(HERE / "sidecmp_art.h").write_text(
    "/* generated by build.py */\n"
    + c_bytes("SIDECMP_BG", raw(background()))
)
if "--art-only" in sys.argv:
    raise SystemExit(0)
sys.path.insert(0, str(HERE.parent / "common"))
from zvis_build import build  # noqa: E402

build(HERE, encode_zoom_rle(cover()))
